const STRINGS: Record<Lang, Strings> = { de, en, fr, es, it, ar };

/** What the venue told us about its languages (from /api/v1/menu). */
export interface VenueLocales {
  defaultLocale?: string | null;
  enabledLocales?: string[] | null;
}

interface I18nApi {
  lang: Lang;
  t: Strings;
  dir: Dir;
  /** Locales this venue enabled that the app also has copy for. Falls
   *  back to the whole catalogue until the menu has loaded. */
  available: readonly Lang[];
  setLang: (lang: Lang) => void;
  /** Called once the menu is known, so the picker and the default can be
   *  narrowed to what the restaurant actually serves. */
  applyVenueLocales: (venue: VenueLocales) => void;
  /**
   * The language on the signed-in guest's ACCOUNT (`/api/v1/me`).
   *
   * Outranks everything else: the device language, the venue default,
   * and this device's own stored choice — which is then overwritten to
   * match, so signing out leaves the guest in the language they were
   * just using rather than snapping back. Null/unknown/not-offered is a
   * no-op, which is what a guest who never picked one looks like.
   */
  applyProfileLocale: (locale: string | null | undefined) => void;
  /**
   * Hold the RTL restart until this work has finished.
   *
   * Switching between Arabic and a left-to-right language restarts the
   * app (see the effect below), and anything still in flight when that
   * happens is simply lost — including the PATCH that saves the language
   * onto the signed-in guest's account, which is exactly what used to
   * bring the app back speaking the OLD language. Whoever fires such a
   * request alongside `setLang` hands the promise to this.
   *
   * Never rejects, never blocks a language change: the restart waits at
   * most `PERSIST_TIMEOUT_MS`, and a language change with no direction
   * change ignores it entirely.
   */
  deferReload: (work: Promise<unknown>) => void;
}

const I18nContext = createContext<I18nApi | null>(null);
const KEY = "rangla-lang";
/** The language the app last flipped the NATIVE direction flag for. Its
 *  only job is to break the restart loop described in the effect below. */
const DIR_KEY = "rangla-lang-dir";
/** How long the restart waits for the choice (and any deferred work) to
 *  be written. Long enough for a slow disk and a round trip, short
 *  enough that a dead network cannot hang the switch. */
const PERSIST_TIMEOUT_MS = 4000;

/**
 * The language to use when the guest has not chosen one, narrowed to
 * what the venue offers.
 *
 * Order: the VENUE's own default locale, then the device's languages,
 * then English, then whatever is left. No AsyncStorage here — this is
 * only the value used until (or unless) the guest picks one.
 *
 * The venue default leads deliberately. This used to try the device
 * first, which meant a German restaurant greeted an English-phone
 * tourist in English while its dish names — the half the restaurant
 * actually authors — were still German unless the owner had filled in
 * an English translation row. One language for the whole app, and the
 * house's own is the one guaranteed complete.
 */
export function deviceDefault(pool: readonly Lang[], venueDefault?: string | null): Lang {
  const choices = pool.length > 0 ? pool : LANG_CODES;
  const house = toLang(venueDefault);
  if (house && choices.includes(house)) return house;
  for (const entry of Localization.getLocales()) {
    const match = toLang(entry.languageCode ?? entry.languageTag);
    if (match && choices.includes(match)) return match;
  }
  return choices.includes("en") ? "en" : (choices[0] ?? "en");
}

export function I18nProvider({ children }: { children: React.ReactNode }): React.ReactElement {
  // Synchronous first guess from the device; the persisted choice (async)
  // and then the venue's locale list refine it.
  const [lang, setLangState] = useState<Lang>(() => deviceDefault(LANG_CODES));
  const [available, setAvailable] = useState<readonly Lang[]>(LANG_CODES);
  /** True once the guest has an explicit stored preference — the venue
   *  list may then only override it if that language is switched off. */
  const chosen = useRef(false);
  /** The persisted choice has been read; before that, nothing may
   *  overwrite `lang` or we'd race the guest's own preference. */
  const [booted, setBooted] = useState(false);
  const venueRef = useRef<VenueLocales | null>(null);
  /** The signed-in guest's account language, once `/api/v1/me` has
   *  answered. A ref because it must survive a late boot and a late
   *  menu, both of which re-decide `lang`. */
  const profileLang = useRef<Lang | null>(null);
  /** `available` for the callbacks, which must stay identity-stable. */
  const availableRef = useRef<readonly Lang[]>(LANG_CODES);

  useEffect(() => {
    AsyncStorage.getItem(KEY)
      .then((saved) => {
        // The account language already won — do not undo it with the
        // value this device happened to have cached.
        if (profileLang.current) return;
        if (isLang(saved)) {
          chosen.current = true;
          setLangState(saved);
        }
      })
      .catch(() => {})
      .finally(() => setBooted(true));
  }, []);

  // Layout direction is a NATIVE, process-wide setting: changing it only
  // takes effect after a reload, so flip it and restart. `allowRTL` has
  // to be called before any forceRTL for the flag to stick.
  const reloading = useRef(false);
  /** Writes and requests the restart below must not cut short. */
  const pending = useRef<Promise<unknown>[]>([]);
  const deferReload = useCallback((work: Promise<unknown>) => {
    // Swallowed here so one failed round trip can never reject the
    // barrier the restart waits on.
    pending.current.push(Promise.resolve(work).catch(() => {}));
  }, []);

  useEffect(() => {
    // Until the persisted choice is read, `lang` is only the device guess.
    // Acting on it here flipped an Arabic device back to LTR and reloaded,
    // after which the stored "ar" flipped it again — an endless reload loop.
    if (!booted || reloading.current) return;
    const dir = dirOf(lang);
    I18nManager.allowRTL(true);
    if ((dir === "rtl") === I18nManager.isRTL) {
      // Flag and language agree: whatever flip got us here worked, so
      // the "already tried" marker has done its job.
      AsyncStorage.removeItem(DIR_KEY).catch(() => {});
      return;
    }
    reloading.current = true;
    void (async () => {
      try {
        // 1. PERSIST FIRST — this is the whole bug. `setLang` fires the
        //    write and returns; restarting a millisecond later killed it
        //    mid-flight, so the app came back reading the PREVIOUS
        //    language out of storage and every screen, menu included,
        //    was in the language the guest had just left. The write is
        //    awaited AND read back before anything native is touched.
        const waiting = pending.current;
        pending.current = [];
        await Promise.race([
          Promise.allSettled([...waiting, AsyncStorage.setItem(KEY, lang)]),
          new Promise((resolve) => setTimeout(resolve, PERSIST_TIMEOUT_MS)),
        ]);
        if ((await AsyncStorage.getItem(KEY)) !== lang) throw new Error("lang not persisted");
        // 2. One flip per language. If the native flag refuses to stick
        //    (it does on some builds), the next launch would see the
        //    same mismatch and restart again, for ever. Having tried
        //    once, live with the direction rather than loop.
        if ((await AsyncStorage.getItem(DIR_KEY)) === lang) {
          reloading.current = false;
          return;
        }
        await AsyncStorage.setItem(DIR_KEY, lang);
        I18nManager.forceRTL(dir === "rtl");
        // Lazily required: expo-updates is unavailable in some dev
        // setups, and a missing module must not crash the switch.
        const Updates: { reloadAsync?: () => Promise<unknown> } = await import("expo-updates");
        if (!Updates.reloadAsync) throw new Error("no reloadAsync");
        await Updates.reloadAsync();
      } catch {
        // Expo Go / dev client with updates disabled, or a storage that
        // would not take the choice: ask for a manual restart, in the
        // language the guest just picked.
        const copy = STRINGS[lang];
        Alert.alert(copy.restartTitle, copy.restartBody);
        reloading.current = false;
      }
    })();
  }, [lang, booted]);

  const resolve = useCallback((venue: VenueLocales) => {
    const enabled = (venue.enabledLocales ?? [])
      .map((code) => toLang(code))
      .filter((code): code is Lang => Boolean(code));
    // Keep the catalogue's own order so the picker never reshuffles, and
    // never end up with an empty list (an old server sends neither field).
    const pool = enabled.length > 0 ? LANG_CODES.filter((c) => enabled.includes(c)) : LANG_CODES;
    availableRef.current = pool;
    setAvailable((current) =>
      current.length === pool.length && current.every((c, i) => c === pool[i]) ? current : pool,
    );
    setLangState((current) => {
      // The signed-in guest's account language outranks this device.
      const account = profileLang.current;
      if (account && pool.includes(account)) return account;
      // Otherwise an explicit choice wins — unless the restaurant
      // switched that language off, in which case fall back rather than
      // show gaps.
      return chosen.current && pool.includes(current)
        ? current
        : deviceDefault(pool, venue.defaultLocale);
    });
  }, []);

  /**
   * Apply the language from the signed-in guest's profile.
   *
   * Ranked above the stored device choice on purpose: the account is the
   * thing that follows the guest between their phone and their tablet,
   * so it is what "my language" means once they are signed in. The local
   * key is rewritten to match so signing out is not a language change.
   *
   * Deliberately stable (refs, not state, in the closure): `auth.tsx`
   * calls this from an effect keyed on the profile, and a changing
   * identity would re-run it on every render.
   */
  const applyProfileLocale = useCallback((locale: string | null | undefined) => {
    const next = toLang(locale);
    // A profile with no language, or one this build has no copy for, is
    // simply no opinion — not a reason to change anything.
    if (!next) return;
    profileLang.current = next;
    // Before the menu lands `availableRef` is the whole catalogue, so
    // this is permissive early and narrows once the venue is known.
    if (!availableRef.current.includes(next)) return;
    chosen.current = true;
    setLangState(next);
    AsyncStorage.setItem(KEY, next).catch(() => {});
  }, []);

  const applyVenueLocales = useCallback(
    (venue: VenueLocales) => {
      venueRef.current = venue;
      if (booted) resolve(venue);
    },
    [booted, resolve],
  );

  // The menu can arrive before the persisted choice does — replay it.
  useEffect(() => {
    if (booted && venueRef.current) resolve(venueRef.current);
  }, [booted, resolve]);

  const api = useMemo<I18nApi>(
    () => ({
      lang,
      t: STRINGS[lang],
      dir: dirOf(lang),
      available,
      setLang: (next) => {
        chosen.current = true;
        setLangState(next);
        AsyncStorage.setItem(KEY, next).catch(() => {});
      },
      applyVenueLocales,
      applyProfileLocale,
      deferReload,
    }),
    [lang, available, applyVenueLocales, applyProfileLocale, deferReload],
  );
  return <I18nContext.Provider value={api}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nApi {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
