export type Strings = (typeof STRINGS)["de"];

interface I18nApi {
  lang: Lang;
  t: Strings;
  setLang: (lang: Lang) => void;
}

const I18nContext = createContext<I18nApi | null>(null);
const KEY = "rangla-lang";

function deviceDefault(): Lang {
  // German is the house default regardless of device locale; the switcher
  // on the Konto screen persists an explicit choice.
  return "de";
}

export function I18nProvider({ children }: { children: React.ReactNode }): React.ReactElement {
  const [lang, setLangState] = useState<Lang>(deviceDefault());
  useEffect(() => {
    AsyncStorage.getItem(KEY).then((saved) => {
      if (saved === "de" || saved === "en") setLangState(saved);
    });
  }, []);
  const api = useMemo<I18nApi>(
    () => ({
      lang,
      t: STRINGS[lang] as Strings,
      setLang: (next) => {
        setLangState(next);
        AsyncStorage.setItem(KEY, next).catch(() => {});
      },
    }),
    [lang],
  );
  return <I18nContext.Provider value={api}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nApi {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
